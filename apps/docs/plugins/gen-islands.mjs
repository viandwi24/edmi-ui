// Astro can only hydrate a component whose import it sees at compile time, so for every demo file we
// generate a tiny wrapper `.astro` that statically imports it with `client:visible`.
// ComponentDemo then renders the wrapper dynamically (glob). Re-run on config load (restart dev to
// pick up brand-new demo files).
import {
	existsSync,
	mkdirSync,
	readdirSync,
	rmSync,
	writeFileSync,
} from "node:fs";
import { join, resolve } from "node:path";

const EXT = { react: ".tsx", vue: ".vue", svelte: ".svelte" };

export function genIslands(docsRoot) {
	const out = resolve(docsRoot, "src/components/islands");
	rmSync(out, { recursive: true, force: true });
	for (const [fw, ext] of Object.entries(EXT)) {
		const dir = resolve(docsRoot, "src/demos", fw);
		if (!existsSync(dir)) continue;
		mkdirSync(join(out, fw), { recursive: true });
		for (const f of readdirSync(dir)) {
			if (!f.endsWith(ext)) continue;
			const base = f.slice(0, -ext.length);
			writeFileSync(
				join(out, fw, `${base}.astro`),
				`---\n// generated by plugins/gen-islands.mjs\nimport Demo from "../../../demos/${fw}/${f}";\n---\n\n<Demo client:visible />\n`,
			);
		}
	}
}
